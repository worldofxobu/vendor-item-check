local VIC = dofile("tests/contribution_fixture.lua")
VIC:OptionsInitialize()
SlashCmdList.VENDORITEMCHECK("export")
assert(VIC.exportPanel:IsVisible() and VIC.exportBox:GetText() == "", "Terms precede export preparation")
VIC.exportPrepare.scripts.OnClick()
local document = VIC.exportBox:GetText()
assert(document:find('"schema":"vic.observations/1"', 1, true))
assert(document:find('"licence":"CC BY%-SA 4.0"'))
assert(document:find('"costs":[]', 1, true), "Empty arrays must be valid JSON arrays")
assert(document:find('Éowyn \\"Vendor\\"', 1, true), "NPC quotes must be JSON-escaped")
assert(not document:find("PRIVATE", 1, true), "Private settings, identifiers and extra fields must not leak")
assert(not document:find("Player-", 1, true) and not document:find("character", 1, true))
assert(VIC.exportBox.focused and VIC.exportBox.highlighted)
VIC:OpenExport()
assert(VIC.exportBox:GetText() == "", "Reopening must clear the previous prepared export")
VIC.exportBox.scripts.OnEscapePressed(VIC.exportBox)
assert(not VIC.exportPanel:IsVisible())
print("=== ALL MANUAL EXPORT SMOKE TESTS PASSED ===")
