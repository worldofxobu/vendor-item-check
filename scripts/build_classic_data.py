#!/usr/bin/env python3
"""
scripts/build_classic_data.py
Builds VendorItemCheck/Data.lua from historical Classic Era references sources.
Zero external python libraries required (standard library only).
"""

import os
import re
import sys
import json
import urllib.request

CACHE_DIR = os.path.join(os.path.dirname(__file__), ".cache")
OUTPUT_FILE = os.path.join(os.path.dirname(__file__), "..", "VendorItemCheck", "Data.lua")

URL_ZONES = "https://raw.githubusercontent.com/shagu/pfQuest/master/db/enUS/zones.lua"
URL_UNIT_NAMES = "https://raw.githubusercontent.com/shagu/pfQuest/master/db/enUS/units.lua"
URL_ITEMS = "https://raw.githubusercontent.com/shagu/pfQuest/master/db/items.lua"
URL_UNITS = "https://raw.githubusercontent.com/shagu/pfQuest/master/db/units.lua"
URL_PRICES = "https://raw.githubusercontent.com/nexus-devs/wow-classic-items/master/data/json/data.json"


def fetch_file(url: str, filename: str) -> str:
    os.makedirs(CACHE_DIR, exist_ok=True)
    cache_path = os.path.join(CACHE_DIR, filename)
    if os.path.exists(cache_path) and os.path.getsize(cache_path) > 0:
        print(f"Using cached {filename}")
        with open(cache_path, "r", encoding="utf-8", errors="ignore") as f:
            return f.read()

    print(f"Downloading {url} ...")
    req = urllib.request.Request(url, headers={"User-Agent": "VendorItemCheck-Builder/1.0"})
    with urllib.request.urlopen(req) as resp:
        content = resp.read().decode("utf-8", errors="ignore")

    with open(cache_path, "w", encoding="utf-8") as f:
        f.write(content)

    return content


def parse_zones(text: str) -> dict[int, str]:
    zones = {}
    for m in re.finditer(r'\[(\d+)\]\s*=\s*\"([^\"]+)\"', text):
        zones[int(m.group(1))] = m.group(2)
    return zones


def parse_unit_names(text: str) -> dict[int, str]:
    names = {}
    for m in re.finditer(r'\[(\d+)\]\s*=\s*\"([^\"]+)\"', text):
        names[int(m.group(1))] = m.group(2)
    return names


def parse_vendor_items(text: str) -> dict[int, list[int]]:
    vendor_items = {}
    for m in re.finditer(r'^  \[(\d+)\]\s*=\s*\{[\r\n]+(.*?)^  \},', text, re.MULTILINE | re.DOTALL):
        iid = int(m.group(1))
        body = m.group(2)
        v_block = re.search(r'\[\"V\"\]\s*=\s*\{([^}]+)\}', body)
        if v_block:
            vids = [int(x) for x in re.findall(r'\[(\d+)\]\s*=', v_block.group(1))]
            if vids:
                vendor_items[iid] = vids
    return vendor_items


def parse_units_data(text: str, needed_vendor_ids: set[int], zones: dict[int, str], unit_names: dict[int, str]):
    vendors = {}
    for m in re.finditer(r'^  \[(\d+)\]\s*=\s*\{[\r\n]+(.*?)^  \},', text, re.MULTILINE | re.DOTALL):
        uid = int(m.group(1))
        if uid not in needed_vendor_ids:
            continue
        body = m.group(2)

        name = unit_names.get(uid, f"Vendor {uid}")
        fac_m = re.search(r'\[\"fac\"\]\s*=\s*\"([^\"]+)\"', body)
        raw_fac = fac_m.group(1) if fac_m else "N"
        fac = "N"
        if raw_fac == "A":
            fac = "A"
        elif raw_fac == "H":
            fac = "H"

        coord_m = re.search(r'\{\s*([\d\.]+)\s*,\s*([\d\.]+)\s*,\s*(\d+)', body)
        zone_name = "Unknown"
        x, y = 0.0, 0.0
        if coord_m:
            x = float(coord_m.group(1))
            y = float(coord_m.group(2))
            z_id = int(coord_m.group(3))
            zone_name = zones.get(z_id, f"Zone {z_id}")

        vendors[uid] = {
            "name": name,
            "zone": zone_name,
            "faction": fac,
            "x": round(x, 1),
            "y": round(y, 1),
        }
    return vendors


def parse_item_prices(text: str) -> dict[int, int]:
    prices = {}
    try:
        data = json.loads(text)
        for entry in data:
            item_id = entry.get("itemId")
            vp = entry.get("vendorPrice")
            if item_id and vp and vp > 0:
                prices[int(item_id)] = int(vp)
    except Exception as e:
        print(f"Warning: Failed to parse item prices JSON: {e}")
    return prices


def escape_lua_string(s: str) -> str:
    return s.replace('\\', '\\\\').replace('"', '\\"')


def generate_lua(vendor_items: dict[int, list[int]], vendors: dict[int, dict], prices: dict[int, int]) -> str:
    lines = []
    lines.append("-- Auto-generated by scripts/build_classic_data.py from historical Classic Era references")
    lines.append("-- DO NOT EDIT MANUALLY")
    lines.append("local _, VIC = ...\n")

    lines.append("-- Vendor registry: [vendorID] = { name, zone, faction, x, y }")
    lines.append("-- faction: 'A' = Alliance, 'H' = Horde, 'N' = Neutral/Both")
    lines.append("VIC.Vendors = {")
    for vid in sorted(vendors.keys()):
        v = vendors[vid]
        name = escape_lua_string(v["name"])
        zone = escape_lua_string(v["zone"])
        fac = v["faction"]
        x = v["x"]
        y = v["y"]
        lines.append(f'    [{vid}] = {{ "{name}", "{zone}", "{fac}", {x}, {y} }},')
    lines.append("}\n")

    lines.append("-- Item registry: [itemID] = { v = { vendorID1, ... }, p = buyPrice }")
    lines.append("VIC.Items = {")
    for item_id in sorted(vendor_items.keys()):
        vids = vendor_items[item_id]
        valid_vids = [vid for vid in vids if vid in vendors]
        if not valid_vids:
            continue
        vids_str = ", ".join(str(vid) for vid in valid_vids)
        price = prices.get(item_id, 0)
        if price > 0:
            lines.append(f"    [{item_id}] = {{ v = {{ {vids_str} }}, p = {price} }},")
        else:
            lines.append(f"    [{item_id}] = {{ v = {{ {vids_str} }} }},")
    lines.append("}\n")

    lines.append('VIC.Datasets = VIC.Datasets or {}')
    lines.append('VIC.Datasets.classic = { vendors = VIC.Vendors, items = VIC.Items, metadata = { client = "Classic Era", source = "pfQuest / wow-classic-items (historical reference)", dataAsOf = "Unrecorded", build = "Classic Era reference; exact build unrecorded" } }')
    lines.append("VIC.Vendors = nil\nVIC.Items = nil")
    return "\n".join(lines)


def main():
    print("=== Building VendorItemCheck Database ===")
    zones_text = fetch_file(URL_ZONES, "zones.lua")
    zones = parse_zones(zones_text)
    print(f"Parsed {len(zones)} zones")

    unit_names_text = fetch_file(URL_UNIT_NAMES, "units_enUS.lua")
    unit_names = parse_unit_names(unit_names_text)
    print(f"Parsed {len(unit_names)} unit names")

    items_text = fetch_file(URL_ITEMS, "items.lua")
    vendor_items = parse_vendor_items(items_text)
    print(f"Parsed {len(vendor_items)} vendor items")

    needed_vendor_ids = set()
    for vids in vendor_items.values():
        needed_vendor_ids.update(vids)
    print(f"Identified {len(needed_vendor_ids)} unique vendor IDs")

    units_text = fetch_file(URL_UNITS, "units.lua")
    vendors = parse_units_data(units_text, needed_vendor_ids, zones, unit_names)
    print(f"Parsed {len(vendors)} vendor records")

    prices = {}
    try:
        prices_text = fetch_file(URL_PRICES, "prices.json")
        prices = parse_item_prices(prices_text)
        print(f"Parsed {len(prices)} item prices")
    except Exception as e:
        print(f"Note: Price parsing skipped or failed ({e}); continuing without prices")

    lua_code = generate_lua(vendor_items, vendors, prices)

    os.makedirs(os.path.dirname(OUTPUT_FILE), exist_ok=True)
    with open(OUTPUT_FILE, "w", encoding="utf-8") as f:
        f.write(lua_code)

    file_size_kb = os.path.getsize(OUTPUT_FILE) / 1024
    print(f"Successfully wrote {OUTPUT_FILE} ({file_size_kb:.1f} KB)")


if __name__ == "__main__":
    main()
